// Run from the project root. Samples the existing production GLB hand path;
// does not change the authored models, runtime motion, or local saved clips.
import {writeFile} from 'node:fs/promises';
import * as T from '../dist/vendor/three.module.js';
import {createDeskHands} from '../dist/game-actors.js';
import {createRiggedPalm} from '../dist/student-assets.js';
import {loadGeometry} from './gltf-geometry.mjs';
const sources=await Promise.all(['hand-left-v3.glb','hand-right-v3.glb','teacher-hand-left-v1.glb','teacher-hand-right-v1.glb'].map(loadGeometry));
const clips={},round=n=>+n.toFixed(7);
for(const id of ['student-walk','student-crawl','teacher-walk']){
 const teacher=id==='teacher-walk',crawl=id==='student-crawl',duration=crawl?1.6:1.2;
 const hands=createDeskHands({createHand:(side,scale)=>{const h=createRiggedPalm(sources[(teacher?2:0)+(side<0?0:1)],side,scale);if(teacher)h.group.userData.characterRole='teacher';return h;}});
 const state={seated:false,freeLook:true,carrying:false,movement:1,crawlBlend:crawl?1:0};
 let time=0;for(let i=0;i<180;i++)hands.update(time+=1/60,{...state,walkPhase:0});
 const keyframes=[];
 for(let i=0;i<8;i++){
  const phase=i*Math.PI*2/7;hands.update(time+=1/60,{...state,walkPhase:phase});hands.group.updateMatrixWorld(true);
  const key={time:round(duration*i/7)};
  for(const side of ['left','right']){const h=hands.getHand(side),e=new T.Euler().setFromQuaternion(h.group.getWorldQuaternion(new T.Quaternion()),'XYZ');key[side]={position:h.group.getWorldPosition(new T.Vector3()).toArray().map(round),rotation:[e.x,e.y,e.z].map(round),curl:round(h.diagnostics().curl)};}
  keyframes.push(key);
 }
 keyframes.at(-1).left=structuredClone(keyframes[0].left);keyframes.at(-1).right=structuredClone(keyframes[0].right);
 clips[id]={duration,loop:true,easing:'smoothstep',keyframes};
}
const source='// Editable baseline sampled from original Tripo first-person hand motion.\n// Generated by qa/sample-hand-baseline59.mjs; never applied without user save.\nexport const HAND_ANIMATION_BASELINE='+JSON.stringify(clips,null,1)+';\n';
await writeFile(new URL('../dist/hand-animation-baseline59.js',import.meta.url),source);
console.log('Sampled 8 source-motion keys for each of the 3 editable clips.');
